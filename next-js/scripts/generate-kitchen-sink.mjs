#!/usr/bin/env node
/* Regenerate components/site/styleguide/kitchen-sink.generated.tsx from the
 * shadcn registry examples in components/styleguide/examples/*-example.tsx
 * (openspec next-design-system § shadcn/ui component set, § Visual parity
 * surface). Run after `npx shadcn add @shadcn/<name>-example` (then
 * `git mv components/<name>-example.tsx components/styleguide/examples/`). */
import { readdirSync, writeFileSync } from "node:fs";

const DIR = new URL("../components/styleguide/examples/", import.meta.url);
const OUT = new URL("../components/site/styleguide/kitchen-sink.generated.tsx", import.meta.url);
// Data (TOC, component list) lives in a server-safe module: a "use client" module's
// non-component exports arrive in Server Components as client references, not values.
const OUT_TOC = new URL(
  "../components/site/styleguide/kitchen-sink-toc.generated.ts",
  import.meta.url,
);

/** Section grouping in the Nuxt styleguide's order; anything unlisted lands in "More". */
const GROUPS = [
  [
    "Form controls",
    [
      "button",
      "button-group",
      "badge",
      "label",
      "input",
      "input-group",
      "input-otp",
      "textarea",
      "native-select",
      "select",
      "checkbox",
      "radio-group",
      "switch",
      "slider",
      "toggle",
      "toggle-group",
      "field",
      "form",
      "combobox",
      "calendar",
    ],
  ],
  [
    "Layout & feedback",
    [
      "card",
      "separator",
      "alert",
      "aspect-ratio",
      "avatar",
      "breadcrumb",
      "kbd",
      "pagination",
      "progress",
      "skeleton",
      "spinner",
      "empty",
      "item",
      "scroll-area",
      "resizable",
      "sonner",
    ],
  ],
  [
    "Overlays & navigation",
    [
      "accordion",
      "alert-dialog",
      "collapsible",
      "context-menu",
      "dialog",
      "drawer",
      "dropdown-menu",
      "hover-card",
      "menubar",
      "navigation-menu",
      "popover",
      "sheet",
      "sidebar",
      "tabs",
      "tooltip",
      "command",
    ],
  ],
  ["Data & complex", ["table", "carousel", "chart"]],
];

const files = readdirSync(DIR)
  .filter((f) => /-example\.tsx$/.test(f))
  .sort();
const names = files.map((f) => f.replace(/-example\.tsx$/, ""));
const pascal = (s) => s.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase()) + "Example";
const title = (s) =>
  s
    .replace(/-/g, " ")
    .replace(/^./, (c) => c.toUpperCase())
    .replace(/\bOtp\b/, "OTP");

const grouped = GROUPS.map(([label, ids]) => [label, ids.filter((id) => names.includes(id))]);
const listed = new Set(grouped.flatMap(([, ids]) => ids));
const more = names.filter((n) => !listed.has(n));
if (more.length) grouped.push(["More", more]);

const imports = names
  .map((n) => `import ${pascal(n)} from "@/components/styleguide/examples/${n}-example";`)
  .join("\n");
const toc = grouped
  .map(
    ([label, ids]) =>
      `  { title: ${JSON.stringify(label)}, items: [${ids.map((id) => `{ id: ${JSON.stringify(id)}, label: ${JSON.stringify(title(id))} }`).join(", ")}] },`,
  )
  .join("\n");
const sections = grouped
  .map(
    ([label, ids]) =>
      `      <h2 className="mb-10 mt-20 font-display text-3xl font-normal uppercase text-ink" data-testid="kitchen-sink-group-heading" data-group=${JSON.stringify(label)}>${label}</h2>\n` +
      ids
        .map(
          (id) =>
            `      <Section id=${JSON.stringify(id)} title=${JSON.stringify(title(id))}>\n        <${pascal(id)} />\n      </Section>`,
        )
        .join("\n"),
  )
  .join("\n");

const out = `/* GENERATED by scripts/generate-kitchen-sink.mjs — do not edit. ${names.length} shadcn/ui registry examples. */
"use client";

import { Section } from "@/components/site/styleguide/Section";
import { Toaster } from "@/components/ui/sonner";
import { TooltipProvider } from "@/components/ui/tooltip";
${imports}

/* Providers the registry examples expect at the app root (tooltips, toasts). */
export function KitchenSink() {
  return (
    <TooltipProvider>
      {/* data-shadcn-scope: app/styleguide/styleguide.css restores shadcn's muted/accent semantics here;
          data-kitchen-sink: the axe gate tracks these vendored examples as a ratcheting baseline. */}
      <div data-shadcn-scope data-kitchen-sink data-testid="kitchen-sink">
${sections}
      </div>
      <Toaster />
    </TooltipProvider>
  );
}
`;
const outToc = `/* GENERATED by scripts/generate-kitchen-sink.mjs — do not edit. Server-safe data for the kitchen sink. */
import type { TocGroup } from "@/components/site/styleguide/Toc";

export const KITCHEN_SINK_TOC: TocGroup[] = [
${toc}
];

export const KITCHEN_SINK_COMPONENTS = ${JSON.stringify(names)} as const;
`;
writeFileSync(OUT, out);
writeFileSync(OUT_TOC, outToc);
console.log(`kitchen sink: ${names.length} examples → ${OUT.pathname} (+ toc)`);
